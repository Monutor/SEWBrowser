/**
 * Чистая часть тумблера блока «Сканы» — без DOM, чтобы покрылась тестами.
 * Разбор ответа гостя (`parseGuestFlag`) лежит в inventory-core: он одинаков
 * для обоих плагинов, его импортирует сам scans-panel.
 */

/** Подсказка на кнопке «Сканы»: что сделает следующий клик. */
export function scansToggleTitle(on: boolean): string {
  return on ? 'Скрыть блок «Сканы»' : 'Показать блок «Сканы»'
}
